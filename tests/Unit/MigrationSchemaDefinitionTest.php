<?php

declare(strict_types=1);

namespace App\Tests\Unit;

use PHPUnit\Framework\TestCase;

/**
 * Static regression checks over the migration SQL text. Runs without a live
 * PostgreSQL; the Section 11 lifecycle gate covers execution against a real
 * disposable database.
 */
final class MigrationSchemaDefinitionTest extends TestCase
{
    private const MIGRATIONS_DIR = __DIR__.'/../../migrations';

    /** @return iterable<string, array{string, string}> */
    public static function tablePlacements(): iterable
    {
        foreach (['users', 'app_sessions', 'password_reset_tokens', 'saved_addresses'] as $table) {
            yield $table => ['Version20261101000000', $table];
        }
        foreach ([
            'categories', 'category_translations', 'brands', 'manufacturers', 'products',
            'product_translations', 'product_variants', 'product_variant_translations',
            'product_images', 'product_specifications',
        ] as $table) {
            yield $table => ['Version20261102000000', $table];
        }
        foreach (['carts', 'cart_items', 'orders', 'order_addresses', 'order_items', 'exchange_rates'] as $table) {
            yield $table => ['Version20261103000000', $table];
        }
        foreach (['payment_sessions', 'payment_attempts', 'shopify_webhook_deliveries'] as $table) {
            yield $table => ['Version20261104000000', $table];
        }
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('tablePlacements')]
    public function testEachTableIsCreatedByItsPlannedMigration(string $migration, string $table): void
    {
        $sql = self::migrationSql($migration);
        self::assertStringContainsString('CREATE TABLE '.$table.' (', $sql);
    }

    /** @return iterable<string, array{string, string}> */
    public static function invariants(): iterable
    {
        yield 'functional email index' => [
            'Version20261101000000',
            'CREATE UNIQUE INDEX users_email_lower_unique ON users (lower(email))',
        ];
        yield 'terms consistency check' => [
            'Version20261101000000',
            'CHECK (accepted_terms = (terms_accepted_at IS NOT NULL))',
        ];
        yield 'reset token one per user' => ['Version20261101000000', 'UNIQUE (user_id)'];
        yield 'cart owner xor' => [
            'Version20261103000000',
            'CHECK ((user_id IS NOT NULL) <> (guest_token IS NOT NULL))',
        ];
        yield 'order totals consistent' => [
            'Version20261103000000',
            'CHECK (total_cents = subtotal_cents + delivery_cents)',
        ];
        yield 'inventory release implies reservation' => [
            'Version20261103000000',
            'inventory_released_at >= inventory_reserved_at',
        ];
        yield 'compare-at above price' => [
            'Version20261102000000',
            'compare_at_price_cents_net IS NULL OR compare_at_price_cents_net >= price_cents_net',
        ];
        yield 'session status partial index' => [
            'Version20261104000000',
            "ON payment_sessions (status) WHERE status <> 'paid'",
        ];
        yield 'attempts never plaintext receipts' => [
            'Version20261104000000',
            'receipt_token_encrypted TEXT',
        ];
        yield 'webhook pending scan index' => [
            'Version20261104000000',
            'ON shopify_webhook_deliveries (processed_at)',
        ];
        yield 'attempt idempotency unique' => ['Version20261104000000', 'UNIQUE (idempotency_key)'];
        yield 'attempt method unique pair' => [
            'Version20261104000000',
            'UNIQUE (payment_session_id, payment_method_hash)',
        ];
        yield 'webhook partial predicate' => [
            'Version20261104000000',
            'WHERE processed_at IS NULL',
        ];
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('invariants')]
    public function testInvariantIsPresent(string $migration, string $needle): void
    {
        self::assertStringContainsString($needle, self::migrationSql($migration));
    }

    public function testNoIfNotExistsAndAllPksAreIdentity(): void
    {
        foreach (glob(self::MIGRATIONS_DIR.'/Version202611*.php') ?: [] as $file) {
            $sql = (string) file_get_contents($file);
            self::assertStringNotContainsString('IF NOT EXISTS', $sql, $file);
            // GENERATED BY DEFAULT: DBAL introspection only detects identity columns
            // declared BY DEFAULT; ALWAYS would permanently fail schema:validate.
            self::assertStringContainsString('GENERATED BY DEFAULT AS IDENTITY', $sql, $file);
            self::assertStringNotContainsString('TIMESTAMP WITHOUT TIME ZONE', $sql, $file);
        }
    }

    public function testMigrationsAbortOnNonPostgresAndHaveDown(): void
    {
        foreach (glob(self::MIGRATIONS_DIR.'/Version202611*.php') ?: [] as $file) {
            $sql = (string) file_get_contents($file);
            self::assertStringContainsString('PostgreSQLPlatform', $sql, $file);
            self::assertStringContainsString('function down(', $sql, $file);
        }
    }

    private static function migrationSql(string $version): string
    {
        $file = self::MIGRATIONS_DIR.'/'.$version.'.php';
        self::assertFileExists($file);

        return (string) file_get_contents($file);
    }
}
